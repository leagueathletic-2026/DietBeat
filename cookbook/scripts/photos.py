#!/usr/bin/env python3
"""Recipe photo pipeline for the BODiQ cookbook.

Each recipe has a `photo:` block (dish / vessel / angle) written together with the recipe.
This script turns it into a full image prompt, and imports the generated images.

  python3 scripts/photos.py prompts [--all] [--ids b01,b02]   # print JSON jobs for recipes still missing a photo
  python3 scripts/photos.py fetch <batch-manifest-url>         # download a generated batch into images/<id>.jpg
  python3 scripts/photos.py check                              # missing photos + near-duplicate detection
  python3 scripts/photos.py sheet [--ids ...]                  # contact sheets for visual review -> output/sheets/

Images are generated with Google Gemini 2.5 Flash Image (via the CodeWords platform) at 21:9;
see content/photo-prompts.md (regenerated by `prompts`) for every prompt used.
"""
import hashlib
import io
import json
import sys
import time
import urllib.request
from pathlib import Path

import yaml
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
IMAGES = ROOT / "images"
MANIFEST = IMAGES / "manifest.json"
TARGET = (1536, 672)  # 21:9 hero photo

# Rotating props so the lime brand accent is present but never identical between photos.
ACCENTS = [
    "a neatly folded neon lime-green linen napkin at the edge of the frame",
    "a small neon lime-green ceramic ramekin in the background, softly out of focus",
    "a neon lime-green ceramic coaster under a small side dish",
    "a neon lime-green enamel spoon resting beside the dish",
    "a strip of neon lime-green cloth under the board",
    "a tiny neon lime-green ceramic salt dish blurred in the background",
]
BACKGROUNDS = [
    "dark charcoal stone surface against a deep black backdrop",
    "black marble surface with subtle grey veins",
    "dark weathered wood table, almost black",
    "matte black concrete surface with soft texture",
    "dark slate surface with a deep grey gradient backdrop",
]


def recipes():
    for path in sorted((ROOT / "recipes").glob("*.yaml")):
        data = yaml.safe_load(path.read_text())
        for r in data.get("recipes") or []:
            yield r


def build_prompt(r, i):
    ph = r["photo"]
    return (
        "Professional editorial food photography for a premium fitness cookbook. "
        f"Subject: {ph['dish']}. Served in {ph['vessel']}. Camera: {ph['angle']}. "
        "Wide 21:9 frame, the dish fully in frame with breathing room, the bottom fifth of the frame is plain dark surface. "
        f"Background: {ph.get('background') or BACKGROUNDS[i % len(BACKGROUNDS)]}. "
        "Lighting: dramatic low-key side light with a soft rim light, rich natural colours, glistening realistic textures, "
        "shallow depth of field, appetizing and natural, real home-cooked portion. "
        f"Brand accent: {ACCENTS[i % len(ACCENTS)]}. "
        "Photorealistic, high detail, shot on a full-frame camera with a 50mm lens. "
        "Only foods from this recipe appear in the frame. Absolutely no text, letters, numbers, codes, logos, watermarks, people or hands."
    )


def cmd_prompts(args):
    want = None
    if "--ids" in args:
        want = set(args[args.index("--ids") + 1].split(","))
    jobs, lines = [], ["# BODiQ — AI photo prompt for every recipe\n",
                       "Model: Google Gemini 2.5 Flash Image (via CodeWords), aspect ratio 21:9.\n"]
    for i, r in enumerate(recipes()):
        if "photo" not in r:
            print(f"warning: {r['id']} has no photo block", file=sys.stderr)
            continue
        p = build_prompt(r, i)
        lines.append(f"## {r['id']} — {r['name']}\n\n{p}\n")
        exists = (IMAGES / f"{r['id']}.jpg").exists()
        if (want and r["id"] in want) or (not want and ("--all" in args or not exists)):
            jobs.append({"id": r["id"], "prompt": p})
    (ROOT / "content" / "photo-prompts.md").write_text("\n".join(lines))
    print(json.dumps(jobs, ensure_ascii=False))


def to_jpeg(data):
    im = Image.open(io.BytesIO(data)).convert("RGB")
    w, h = im.size
    tw, th = TARGET
    # center-crop to 21:9 then resize
    if w / h > tw / th:
        nw = int(h * tw / th); im = im.crop(((w - nw) // 2, 0, (w - nw) // 2 + nw, h))
    else:
        nh = int(w * th / tw); im = im.crop((0, (h - nh) // 2, w, (h - nh) // 2 + nh))
    im = im.resize(TARGET, Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, "JPEG", quality=90, optimize=True, progressive=True)
    return buf.getvalue(), im


def ahash(im, size=16):
    g = im.convert("L").resize((size, size), Image.LANCZOS)
    px = list(g.getdata()); avg = sum(px) / len(px)
    return "".join("1" if p > avg else "0" for p in px)


def get(url):
    for attempt in range(4):
        try:
            with urllib.request.urlopen(url, timeout=60) as r:
                return r.read()
        except Exception as e:  # network hiccup: retry with backoff
            if attempt == 3:
                raise
            time.sleep(2 ** (attempt + 1))


def cmd_fetch(args):
    batch = json.loads(get(args[0]))
    manifest = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    prompts = {r["id"]: build_prompt(r, i) for i, r in enumerate(recipes()) if "photo" in r}
    ok = 0
    for item in batch:
        rid = item["id"]
        if not item.get("url"):
            print(f"{rid}: FAILED in generation ({item.get('error', '')[:120]})")
            continue
        jpg, im = to_jpeg(get(item["url"]))
        (IMAGES / f"{rid}.jpg").write_bytes(jpg)
        manifest[rid] = {
            "file": f"{rid}.jpg", "model": item.get("model", "gemini-2.5-flash-image"),
            "prompt": item.get("prompt") or prompts.get(rid), "source_url": item["url"],
            "sha256": hashlib.sha256(jpg).hexdigest(), "ahash": ahash(im),
            "generated": time.strftime("%Y-%m-%d"),
        }
        ok += 1
    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=1, sort_keys=True))
    print(f"imported {ok}/{len(batch)} photos")


def cmd_check(args):
    manifest = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    ids = [r["id"] for r in recipes()]
    missing = [i for i in ids if not (IMAGES / f"{i}.jpg").exists()]
    print(f"recipes: {len(ids)}  photos: {len(ids) - len(missing)}  missing: {len(missing)}")
    if missing:
        print("missing:", ",".join(missing))
    hashes = {k: v["ahash"] for k, v in manifest.items() if k in ids}
    shas = {}
    for k, v in manifest.items():
        shas.setdefault(v["sha256"], []).append(k)
    dups = [v for v in shas.values() if len(v) > 1]
    near = []
    keys = sorted(hashes)
    for a in range(len(keys)):
        for b in range(a + 1, len(keys)):
            d = sum(x != y for x, y in zip(hashes[keys[a]], hashes[keys[b]]))
            if d <= 20:  # of 256 bits
                near.append((keys[a], keys[b], d))
    print("identical files:", dups or "none")
    print("near-duplicates (ahash distance <= 20/256):", near or "none")


def cmd_sheet(args):
    ids = [r["id"] for r in recipes()]
    names = {r["id"]: r["name"] for r in recipes()}
    if "--ids" in args:
        ids = args[args.index("--ids") + 1].split(",")
    ids = [i for i in ids if (IMAGES / f"{i}.jpg").exists()]
    out = ROOT / "output" / "sheets"; out.mkdir(parents=True, exist_ok=True)
    font = ImageFont.load_default(size=22)
    per = 8
    for s in range(0, len(ids), per):
        chunk = ids[s:s + per]
        tw, th = 768, 336
        sheet = Image.new("RGB", (tw * 2, (th + 34) * ((len(chunk) + 1) // 2)), "black")
        d = ImageDraw.Draw(sheet)
        for k, rid in enumerate(chunk):
            im = Image.open(IMAGES / f"{rid}.jpg").resize((tw, th))
            x, y = (k % 2) * tw, (k // 2) * (th + 34)
            sheet.paste(im, (x, y + 34))
            d.text((x + 8, y + 5), rid, fill=(184, 242, 58), font=font)
        f = out / f"sheet-{s // per + 1:02d}.jpg"
        sheet.save(f, quality=80)
        print(f, " ".join(chunk))


if __name__ == "__main__":
    cmd, *rest = sys.argv[1:] or ["help"]
    {"prompts": cmd_prompts, "fetch": cmd_fetch, "check": cmd_check, "sheet": cmd_sheet}.get(
        cmd, lambda a: print(__doc__))(rest)
